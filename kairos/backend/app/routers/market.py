@router.get("/options/underlyings")
def option_underlyings(db: Session = Depends(get_db), _: User = Depends(current_user)):
    t = sim.now_ts()
    out = []
    for s in _visible(db):
        if s.has_options:
            cfg = s.meta.get("options") or {}
            out.append({
                "symbol": s.symbol,
                "name": s.name,
                "spot": mkt.spec_price(s, t),
                "lot_size": cfg.get("lot_size"),
                "strike_step": cfg.get("strike_step"),
                "expiries": [e.isoformat() for e in mkt.expiries_for(s, t)],
                "weekly": bool(cfg.get("weekly")),
            })
    return {"underlyings": out, "simulated": True}


@router.get("/options/chain/{underlying}")
def option_chain(
    underlying: str,
    expiry: str | None = Query(default=None, description="ISO date YYYY-MM-DD"),
    strikes: int = Query(default=12, ge=4, le=25),
    db: Session = Depends(get_db),
    _: User = Depends(current_user),
):
    spec = mkt.get_spec(db, underlying.upper())
    if spec is None or not spec.has_options or not spec.enabled:
        raise HTTPException(404, "No options available for this underlying")
    exps = mkt.expiries_for(spec)
    chosen = exps[0]
    if expiry:
        match = [e for e in exps if e.date().isoformat() == expiry[:10]]
        if not match:
            raise HTTPException(404, "Expiry not listed")
        chosen = match[0]
    chain = mkt.option_chain(db, spec.symbol, chosen, strikes)
    chain["expiries"] = [e.isoformat() for e in exps]
    chain["disclaimer"] = DISCLAIMER
    return chain


# WebSocket: simulated live quotes --------------------------------------------


@router.websocket("/ws")
async def quotes_ws(ws: WebSocket):
    """Streams simulated quotes for subscribed symbols every 2 seconds.

    Client sends {"subscribe": ["RELIANCE", "BTC"]}. Auth via session cookie.
    """
    from ..security import _lookup
    from ..security import settings as sec_settings

    token = ws.cookies.get(sec_settings.session_cookie_name) or ws.query_params.get("token")
    db = SessionLocal()
    try:
        if not token or not _lookup(db, token):
            await ws.close(code=4401)
            return
    finally:
        db.close()
    await ws.accept()
    symbols: list[str] = []

    async def receiver():
        nonlocal symbols
        while True:
            msg = await ws.receive_text()
            try:
                data = json.loads(msg)
                symbols = [str(s)[:48] for s in data.get("subscribe", [])][:60]
            except (ValueError, AttributeError):
                continue

    recv = asyncio.create_task(receiver())
    try:
        while True:
            if symbols:
                db = SessionLocal()
                try:
                    t = sim.now_ts()
                    out = {}
                    for sym in symbols:
                        c = mkt.parse_option_symbol(sym)
                        if c:
                            if mkt.get_spec(db, c.underlying):
                                q = mkt.option_quote(db, c, t)
                                out[sym] = {"ltp": q["ltp"], "change": q["change"], "change_pct": q["change_pct"]}
                            continue
                        spec = mkt.get_spec(db, sym)
                        if spec and spec.enabled:
                            q = mkt.quote(spec, t)
                            out[sym] = {k: q[k] for k in ("ltp", "change", "change_pct", "bid", "ask", "high", "low", "volume")}
                finally:
                    db.close()
                await ws.send_text(json.dumps({"type": "quotes", "t": t, "data": out, "simulated": True}))
            await asyncio.sleep(2)
    except (WebSocketDisconnect, RuntimeError):
        pass
    finally:
        recv.cancel()
