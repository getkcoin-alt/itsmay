router = APIRouter(prefix="/api/market", tags=["market"])

DISCLAIMER = "Simulated demonstration data generated by a deterministic model. Not real market prices."


def _visible(db: Session, asset_class: str | None = None, include_disabled: bool = False) -> list[mkt.Spec]:
    specs = [s for s in mkt.load_specs(db).values() if include_disabled or s.enabled]
    if asset_class:
        specs = [s for s in specs if s.asset_class == asset_class]
    return sorted(specs, key=lambda s: s.sort_order)


@router.get("/instruments")
def instruments(
    asset_class: str | None = Query(default=None, pattern="^(stock|crypto|forex|index)$"),
    q: str | None = Query(default=None, max_length=40),
    db: Session = Depends(get_db),
    _: User = Depends(current_user),
):
    specs = _visible(db, asset_class)
    if q:
        needle = q.strip().lower()
        specs = [s for s in specs if needle in s.symbol.lower() or needle in s.name.lower()]
    t = sim.now_ts()
    inr_only = get_settings_doc(db)["trading"].get("forex_inr_pairs_only")
    out = []
    for s in specs:
        quote = mkt.quote(s, t)
        if s.asset_class == "forex" and inr_only and s.currency != "INR":
            quote["tradable"] = False
            quote["restriction"] = "Not permitted under current jurisdiction setting"
        out.append(quote)
    return {"instruments": out, "disclaimer": DISCLAIMER, "simulated": True}


@router.get("/overview")
def overview(db: Session = Depends(get_db), _: User = Depends(current_user)):
    t = sim.now_ts()
    quotes = [mkt.quote(s, t) for s in _visible(db)]
    tradables = [q for q in quotes if q["asset_class"] != "index"]

    def top(cls: str | None, key: str, n: int = 5, reverse: bool = True):
        rows = [q for q in tradables if cls is None or q["asset_class"] == cls]
        return sorted(rows, key=lambda q: q[key], reverse=reverse)[:n]

    breadth = {
        cls: {
            "advancers": sum(1 for q in tradables if q["asset_class"] == cls and q["change"] > 0),
            "decliners": sum(1 for q in tradables if q["asset_class"] == cls and q["change"] < 0),
        }
        for cls in ("stock", "crypto", "forex")
    }
    return {
        "indices": [q for q in quotes if q["asset_class"] == "index"],
        "gainers": top("stock", "change_pct"),
        "losers": top("stock", "change_pct", reverse=False),
        "most_active": sorted([q for q in tradables if q["asset_class"] == "stock"], key=lambda q: q["volume"] * q["ltp"], reverse=True)[:5],
        "crypto_movers": sorted([q for q in tradables if q["asset_class"] == "crypto"], key=lambda q: abs(q["change_pct"]), reverse=True)[:5],
        "forex": [q for q in tradables if q["asset_class"] == "forex"],
        "breadth": breadth,
        "session": {
            "label": "Simulated 24×7 session",
            "server_time": datetime.fromtimestamp(t, sim.IST).isoformat(),
        },
        "disclaimer": DISCLAIMER,
        "simulated": True,
    }


@router.get("/quote/{symbol}")
def quote(symbol: str, db: Session = Depends(get_db), _: User = Depends(current_user)):
    c = mkt.parse_option_symbol(symbol)
    if c:
        if mkt.get_spec(db, c.underlying) is None:
            raise HTTPException(404, "Unknown instrument")
        return {"quote": mkt.option_quote(db, c), "disclaimer": DISCLAIMER}
    spec = mkt.get_spec(db, symbol.upper())
    if spec is None or not spec.enabled:
        raise HTTPException(404, "Unknown instrument")
    q = mkt.quote(spec)
    q["about"] = _about(spec)
    return {"quote": q, "disclaimer": DISCLAIMER}


def _about(spec: mkt.Spec) -> dict:
    if spec.asset_class == "stock":
        mcap = spec.base_price * spec.meta.get("base_volume", 1) * 420
        return {"market_cap_sim": mcap, "pe_sim": round(14 + 30 * sim.hash01(spec.symbol, "pe"), 1),
                "div_yield_sim": round(2.5 * sim.hash01(spec.symbol, "dy"), 2), "sector": spec.sector}
    if spec.asset_class == "crypto":
        return {"network": spec.name, "settlement": "Simulated spot (no on-chain transfer)"}
    if spec.asset_class == "forex":
        return {"contract_size": spec.lot_size, "base_ccy": spec.symbol[:3], "quote_ccy": spec.currency,
                "product": "Simulated margin (CFD-style) position"}
    return {}


@router.get("/candles/{symbol}")
def candles(
    symbol: str,
    range_: str = Query(default="1M", alias="range", pattern="^(1D|1W|1M|3M|6M|1Y|5Y)$"),
    db: Session = Depends(get_db),
    _: User = Depends(current_user),
):
    c = mkt.parse_option_symbol(symbol)
    if c:
        # Option premium history (5-minute bars over the last day, hourly for longer).
        interval, span = ("5m", 86400) if range_ == "1D" else ("1h", 7 * 86400)
        step = mkt.INTERVALS[interval]
        t = sim.now_ts()
        bars = []
        start = (int(t - span) // step) * step
        for o_t in range(start, int(t), step):
            pts = [mkt.option_price(db, c, o_t + step * j / 4)["price"] for j in range(5)]
            bars.append({"time": o_t, "open": pts[0], "high": max(pts), "low": min(pts), "close": pts[-1], "volume": 0})
        return {"symbol": symbol, "interval": interval, "candles": bars, "simulated": True}
    spec = mkt.get_spec(db, symbol.upper())
    if spec is None:
        raise HTTPException(404, "Unknown instrument")
    interval, span = mkt.RANGES[range_]
    count = min(400, int(span / mkt.INTERVALS[interval]) + 1)
    return {"symbol": spec.symbol, "interval": interval, "candles": mkt.candles(spec, interval, count), "simulated": True}


