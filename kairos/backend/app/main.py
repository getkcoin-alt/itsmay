"""Kairos simulated multi-asset trading platform — API entrypoint."""

from __future__ import annotations

import asyncio
import logging
from contextlib import asynccontextmanager

from fastapi import FastAPI, Request
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import JSONResponse
from sqlalchemy import text

from .config import get_settings
from .db import SessionLocal
from .routers import admin, auth, market, trading
from .security import csrf_ok, limiter
from .trading import engine

log = logging.getLogger("kairos")
settings = get_settings()


async def _matcher_loop() -> None:
    """Periodically fill resting limit orders and settle expired options."""
    while True:
        await asyncio.sleep(settings.matcher_interval_seconds)
        try:
            await asyncio.to_thread(_match_once)
        except Exception:  # noqa: BLE001 - keep the loop alive
            log.exception("matcher iteration failed")


def _match_once() -> None:
    db = SessionLocal()
    try:
        engine.settle_expiries(db)
        engine.match_open_orders(db)
    finally:
        db.close()


@asynccontextmanager
async def lifespan(_: FastAPI):
    task = asyncio.create_task(_matcher_loop()) if settings.background_matcher else None
    yield
    if task:
        task.cancel()


app = FastAPI(
    title="Kairos Markets API (Simulated)",
    version="1.0.0",
    description=(
        "Demonstration API for a simulated multi-asset trading platform. "
        "All prices are generated by a deterministic model; no real orders, payments or custody exist."
    ),
    lifespan=lifespan,
    docs_url="/api/docs",
    openapi_url="/api/openapi.json",
)

if settings.cors_origins:
    app.add_middleware(
        CORSMiddleware,
        allow_origins=[o.strip() for o in settings.cors_origins.split(",") if o.strip()],
        allow_credentials=True,
        allow_methods=["GET", "POST", "PATCH", "PUT", "DELETE"],
        allow_headers=["content-type", "x-kairos-client", "authorization"],
    )


@app.middleware("http")
async def security_middleware(request: Request, call_next):
    if request.url.path.startswith("/api/") and not csrf_ok(request):
        return JSONResponse({"detail": "Missing client header (CSRF protection)"}, status_code=403)
    response = await call_next(request)
    response.headers["X-Content-Type-Options"] = "nosniff"
    response.headers["X-Frame-Options"] = "DENY"
    response.headers["Referrer-Policy"] = "strict-origin-when-cross-origin"
    response.headers["X-Simulated-Data"] = "true"
    if request.url.path.startswith("/api/") and request.url.path not in ("/api/docs", "/api/openapi.json"):
        response.headers["Cache-Control"] = "no-store"
    return response


app.include_router(auth.router)
app.include_router(market.router)
app.include_router(trading.router)
app.include_router(admin.router)


@app.get("/api/health")
def health():
    db = SessionLocal()
    try:
        db.execute(text("SELECT 1"))
        ok = True
    except Exception:  # noqa: BLE001
        ok = False
    finally:
        db.close()
    return {"status": "ok" if ok else "degraded", "database": ok, "rate_limiter": limiter.backend, "simulated": True}
